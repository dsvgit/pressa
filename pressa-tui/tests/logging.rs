// ============================================================================
// ЭТОТ ФАЙЛ — ТЕСТ. Он проверяет систему логирования (журналирования) программы:
// куда именно пишутся логи (записи о работе программы) и что они реально
// записываются на диск.
//
// tracing — это популярная библиотека Rust для логирования: она позволяет
// писать в коде что-то вроде tracing::info!("что-то произошло"), а библиотека
// сама решает, куда это "что-то" отправить (в файл, в консоль и т.п.).
//
// Правило проекта простыми словами:
// Все логи должны попадать ТОЛЬКО в файл .pressa/pressa.log внутри папки
// проекта пользователя — и никуда больше (не в консоль, не в другой файл).
// ============================================================================

//! Это комментарий "ко всему модулю" (//!). Он объясняет главное правило файла
//! и ссылается на документацию: AGENTS.md и docs/architecture.md, раздел 3.1.
//! `tracing` (сама библиотека логирования) должна писать в `.pressa/pressa.log`
//! и больше никуда.

// "use" подключает готовые инструменты, как import в других языках.
use std::fs; // fs — работа с файлами: создать, прочитать, удалить
use std::path::{Path, PathBuf}; // Path — "путь к файлу" (только посмотреть),
// PathBuf — "путь к файлу" (можно владеть/менять)

// Функция создаёт ВРЕМЕННУЮ папку для теста — что-то вроде "черновика",
// который не мешает реальным файлам проекта.
fn temp_project(name: &str) -> PathBuf {
    // env!("CARGO_TARGET_TMPDIR") — специальная временная папка, которую Cargo
    // (менеджер сборки Rust) выделяет именно для тестов.
    // .join(name) — добавляем к этому пути ещё и подпапку с именем `name`.
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(name);

    // На всякий случай удаляем эту папку, если она вдруg осталась от
    // предыдущего запуска теста (чтобы тест был "чистым" каждый раз).
    // "let _ = ..." значит: "выполни это действие, а результат (успех/ошибка)
    // нам не важен — не будем его проверять".
    let _ = fs::remove_dir_all(&dir);

    // Создаём папку заново, с нуля. .expect(...) значит: "если не получилось
    // создать папку — упади с этой ошибкой", потому что без папки тест
    // продолжать бессмысленно.
    fs::create_dir_all(&dir).expect("временная папка проекта");

    dir // возвращаем путь к готовой (пустой) временной папке
}

