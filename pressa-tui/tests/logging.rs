#[test] // помечает функцию как автоматический тест
fn the_log_lives_in_the_projects_dot_pressa_directory() {
    // Тест №1: проверяем не запись в реальный файл, а просто "формулу" —
    // правильно ли функция log_path() ВЫЧИСЛЯЕТ путь к файлу лога,
    // не создавая при этом никаких файлов на диске.

    // Берём произвольный, даже не существующий, путь к "проекту" — для теста
    // реальная папка не нужна, важна только логика построения пути.
    let project = Path::new("/some/project");

    // assert_eq! — "проверь, что два значения равны; если нет — тест упадёт
    // и покажет оба значения, чтобы было видно, в чём разница".
    assert_eq!(
        // Левая часть: то, что реально возвращает наша функция log_path
        // из модуля logging коробки pressa_tui.
        pressa_tui::logging::log_path(project),
        // Правая часть: то, что мы ОЖИДАЕМ увидеть — путь вида
        // /some/project/.pressa/pressa.log
        project.join(".pressa").join("pressa.log")
    );
}

#[test]
fn init_creates_the_log_file_and_records_events_in_it() {
    // Тест №2: проверяем "по-настоящему" — что логирование реально работает:
    // включаем его, пишем одно сообщение, а потом читаем файл с диска
    // и убеждаемся, что сообщение туда попало.

    // Создаём чистую временную папку специально для этого теста
    // (чтобы тесты не мешали друг другу, если их несколько).
    let project = temp_project("logging-init");

    // Включаем (инициализируем) систему логирования для этой временной папки.
    // .expect(...) — если инициализация не удалась, тест сразу упадёт
    // с этим сообщением об ошибке.
    // Второй аргумент (с T6) — уровень логирования: какие сообщения писать.
    // LogLevel::Info значит "писать info и всё, что важнее" (warn, error).
    pressa_tui::logging::init(&project, pressa_tui::cli::LogLevel::Info)
        .expect("tracing инициализируется");

    // Пишем тестовое сообщение в лог через макрос tracing::info!.
    // step = 1 — это "структурированное поле": не просто текст, а ещё и
    // дополнительные данные (число 1 под именем "step"), которые тоже
    // попадут в запись лога.
    tracing::info!(step = 1, "skeleton is awake");

    // Читаем содержимое файла лога с диска как обычный текст.
    // Путь к файлу снова вычисляем через ту же функцию log_path,
    // что и в первом тесте — чтобы не дублировать логику руками.
    let log =
        fs::read_to_string(pressa_tui::logging::log_path(&project)).expect("файл лога существует");

    // Проверяем, что наше текстовое сообщение реально попало в файл.
    // "{log:?}" в сообщении об ошибке — это отладочный вывод строки log,
    // он покажется в консоли, если проверка не пройдёт, — так удобно
    // сразу увидеть, что на самом деле оказалось в файле.
    assert!(log.contains("skeleton is awake"), "log was: {log:?}");

    // Проверяем, что и структурированное поле (step=1) тоже записалось —
    // то есть tracing действительно сохраняет не только текст сообщения,
    // но и дополнительные данные при нём.
    assert!(log.contains("step=1"), "log was: {log:?}");
}
